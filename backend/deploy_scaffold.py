"""Deterministic container/deploy scaffolding for a generated app.

The agents write application code, not a working container setup - and
`gcloud run deploy --source .` against a folder that holds *both* a Next.js app
and a FastAPI app, with no Dockerfile and a locally-installed `node_modules`,
does not produce a running service. This module writes a known-good scaffold
into the job workspace right after a verified build:

* ``.gcloudignore`` / ``.dockerignore`` - keep ``node_modules`` / ``.next`` out
  of the build context (they're huge once the testing agent has run).
* ``Dockerfile`` - Node 20 image, installs JS deps, installs Python deps when a
  FastAPI backend was generated, runs ``next build``.
* ``start.sh`` - launches ``uvicorn`` on an internal port (when ``api/main.py``
  exists) and serves Next.js on Cloud Run's ``$PORT``.
* ``next.config.mjs`` - only when a FastAPI backend exists: rewrites
  ``/api/*`` to the internal uvicorn port so the single Cloud Run service
  fronts both. Any LLM-written ``next.config.*`` is replaced in that case
  (it is otherwise boilerplate) so the rewrite is guaranteed to apply.

Everything is best-effort: a failure writing one file never aborts the phase.
"""
import json
from pathlib import Path
from typing import List

_IGNORE_LINES = """\
node_modules
.next
out
.git
.gitignore
__pycache__
**/__pycache__
*.pyc
venv
.venv
*.log
.DS_Store
.env
.env.local
"""

_DOCKERFILE = """\
# syntax=docker/dockerfile:1
# Auto-generated by Sketch2Cloud. Builds the generated Next.js app; when a
# FastAPI backend was generated under api/, start.sh also runs it on an internal
# port and Next rewrites /api/* to it. Cloud Run supplies $PORT.
FROM node:20-slim

ENV NEXT_TELEMETRY_DISABLED=1 \\
    PYTHONUNBUFFERED=1

RUN apt-get update \\
 && apt-get install -y --no-install-recommends python3 python3-pip \\
 && rm -rf /var/lib/apt/lists/*

WORKDIR /app

COPY package*.json ./
RUN npm ci --no-audit --no-fund || npm install --no-audit --no-fund

COPY . .

RUN if [ -f requirements.txt ]; then pip3 install --no-cache-dir --break-system-packages -r requirements.txt; fi \\
 && if [ -f api/requirements.txt ]; then pip3 install --no-cache-dir --break-system-packages -r api/requirements.txt; fi

RUN npm run build

RUN chmod +x ./start.sh
ENV NODE_ENV=production
EXPOSE 8080
CMD ["./start.sh"]
"""

_START_SH = """\
#!/bin/sh
# Auto-generated by Sketch2Cloud.
set -e
export NODE_ENV=production
PORT="${PORT:-8080}"
export PORT

if [ -f api/main.py ]; then
  echo "[start] launching FastAPI (uvicorn) on 127.0.0.1:8000"
  python3 -m uvicorn api.main:app --host 127.0.0.1 --port 8000 &
fi

echo "[start] launching Next.js on 0.0.0.0:${PORT}"
exec npm run start -- -p "${PORT}" -H 0.0.0.0
"""

_NEXT_CONFIG_WITH_PROXY = """\
/** @type {import('next').NextConfig} */
// Auto-generated by Sketch2Cloud: front the co-located FastAPI service.
const nextConfig = {
  async rewrites() {
    return [
      { source: '/api/:path*', destination: 'http://127.0.0.1:8000/api/:path*' },
    ];
  },
};

export default nextConfig;
"""

_MINIMAL_API_REQUIREMENTS = """\
fastapi
uvicorn[standard]
pydantic
"""

_NEXT_CONFIG_NAMES = ("next.config.js", "next.config.mjs", "next.config.ts", "next.config.cjs")


def _write(path: Path, content: str, written: List[str]) -> None:
    try:
        # Force LF: these files run inside a Linux container, and a CRLF
        # shebang in start.sh ("#!/bin/sh\r") is an invalid interpreter.
        path.write_text(content, encoding="utf-8", newline="\n")
        written.append(path.name)
    except Exception:
        pass


def _patch_package_json(workspace_dir: Path) -> None:
    """Ensure the standard build/start scripts exist so the Dockerfile works."""
    pkg_path = workspace_dir / "package.json"
    if not pkg_path.exists():
        return
    try:
        pkg = json.loads(pkg_path.read_text(encoding="utf-8"))
    except Exception:
        return
    scripts = pkg.setdefault("scripts", {})
    changed = False
    if not scripts.get("build"):
        scripts["build"] = "next build"
        changed = True
    if not scripts.get("start"):
        scripts["start"] = "next start"
        changed = True
    if changed:
        try:
            pkg_path.write_text(json.dumps(pkg, indent=2) + "\n", encoding="utf-8", newline="\n")
        except Exception:
            pass


def write_deploy_scaffold(workspace_dir: Path) -> List[str]:
    """Write the deploy scaffold into ``workspace_dir``. Returns the filenames
    written (empty when there's no ``package.json`` to deploy)."""
    workspace_dir = Path(workspace_dir)
    if not (workspace_dir / "package.json").exists():
        return []

    written: List[str] = []
    has_fastapi = (workspace_dir / "api" / "main.py").exists()

    _write(workspace_dir / ".gcloudignore", _IGNORE_LINES, written)
    _write(workspace_dir / ".dockerignore", _IGNORE_LINES, written)
    _write(workspace_dir / "Dockerfile", _DOCKERFILE, written)
    _write(workspace_dir / "start.sh", _START_SH, written)
    _patch_package_json(workspace_dir)

    if has_fastapi:
        # Guarantee the /api proxy rewrite: drop any LLM-written next config
        # (boilerplate) and install ours as the single .mjs variant.
        for name in _NEXT_CONFIG_NAMES:
            p = workspace_dir / name
            if p.exists():
                try:
                    p.unlink()
                except Exception:
                    pass
        _write(workspace_dir / "next.config.mjs", _NEXT_CONFIG_WITH_PROXY, written)

        if not (workspace_dir / "requirements.txt").exists() and not (workspace_dir / "api" / "requirements.txt").exists():
            (workspace_dir / "api").mkdir(parents=True, exist_ok=True)
            _write(workspace_dir / "api" / "requirements.txt", _MINIMAL_API_REQUIREMENTS, written)

    return written
